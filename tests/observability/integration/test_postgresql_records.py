"""Persisted observability compatibility and filtering through the real backend."""

from datetime import datetime, timedelta, timezone
import os
import uuid

import pytest
import sqlalchemy as sa
from sqlmodel import col

from inkcre_core import Core
from inkcre_core.libs.obsrv.backends import PostgreSQLBackend
from inkcre_core.libs.obsrv.log_record import LogModel
from inkcre_core.libs.obsrv.records import ObservationQuery, ObservationRecord
from tests.database import TestSession


pytestmark = pytest.mark.skipif(
  not os.getenv("INKCRE_TEST_DATABASE_URL"),
  reason="requires an explicitly selected migrated PostgreSQL runtime",
)


def test_records_survive_reopen_and_filter_before_limit(async_runner):
  operation = f"test.obsrv.{uuid.uuid4().hex}"
  now = datetime(2026, 11, 4, 1, 2, 3, tzinfo=timezone.utc)
  legacy_ids: list[str] = []
  records = [
    ObservationRecord(
      id="modern",
      timestamp=now,
      kind="event",
      event_name="job.closed",
      body="100%_done",
      severity_number=17,
      severity_text="ERROR",
      attributes={"inkcre.job.id": 12, "inkcre.operation": operation},
    ),
    # Newer rows must be excluded before the page is truncated.
    ObservationRecord(
      id="wrong-job",
      timestamp=now + timedelta(seconds=3),
      body="100%_done",
      severity_number=17,
      attributes={"inkcre.job.id": 13, "inkcre.operation": operation},
    ),
    ObservationRecord(
      id="wildcard-decoy",
      timestamp=now + timedelta(seconds=4),
      body="100XXdone",
      severity_number=17,
      attributes={"inkcre.job.id": 12, "inkcre.operation": operation},
    ),
    ObservationRecord(
      id="low-severity",
      timestamp=now + timedelta(seconds=5),
      body="100%_done",
      severity_number=9,
      attributes={"inkcre.job.id": 12, "inkcre.operation": operation},
    ),
  ]

  async def write():
    writer = Core(os.environ["INKCRE_TEST_DATABASE_URL"])
    try:
      await PostgreSQLBackend(writer.sessions).write(records)
    finally:
      await writer.aclose()

  async def read():
    # A different engine/session proves persisted data, not an in-memory receipt.
    reader = Core(os.environ["INKCRE_TEST_DATABASE_URL"])
    try:
      backend = PostgreSQLBackend(reader.sessions)
      query = ObservationQuery(
        since=now - timedelta(seconds=1),
        until=now + timedelta(seconds=10),
        operation=operation,
        job_id=12,
        text="100%_done",
        severity_min=13,
        limit=2,
      )
      page = await backend.query(query)
      assert page.backend == "postgresql" and page.truncated
      assert [record.body for record in page.records] == [
        "trace 100%_done",
        "legacy 100%_done",
      ]
      assert [record.kind for record in page.records] == ["log", "log"]
      assert [record.id for record in page.records] == legacy_ids
      assert [record.event_name for record in page.records] == [None, None]
      assert page.records[0].attributes["legacy"] == {"nested": True}
      complete = await backend.query(query.model_copy(update={"limit": 3}))
      assert not complete.truncated
      assert [record.id for record in complete.records[:2]] == legacy_ids
      assert [record.event_name for record in complete.records[:2]] == [None, None]
      assert [record.body for record in complete.records] == [
        "trace 100%_done",
        "legacy 100%_done",
        "100%_done",
      ]
      modern = complete.records[-1]
      assert modern.id == "modern" and modern.kind == "event"
      assert modern.event_name == "job.closed"
      assert modern.attributes == {"inkcre.job.id": 12, "inkcre.operation": operation}
      events = await backend.query(query.model_copy(update={"kind": "event"}))
      assert [record.id for record in events.records] == ["modern"]
      assert not events.truncated
    finally:
      await reader.aclose()

  try:
    async_runner.run(write())
    # Independent pre-unification storage fixtures cannot be generated by the writer.
    with TestSession() as session:
      legacy_rows = [
        LogModel(
          timestamp=now + timedelta(seconds=1),
          severity_number=17,
          severity_text="ERROR",
          body="legacy 100%_done",
          attributes={"job_id": 12, "inkcre.operation": operation},
        ),
        LogModel(
          timestamp=now + timedelta(seconds=2),
          severity_number=17,
          severity_text="ERROR",
          body="trace 100%_done",
          trace_id="job.12",
          attributes={"legacy": {"nested": True}, "inkcre.operation": operation},
        ),
      ]
      session.add_all(legacy_rows)
      session.commit()
      assert all(row.id is not None for row in legacy_rows)
      legacy_ids = [f"pg.{row.id}" for row in reversed(legacy_rows)]
    async_runner.run(read())
  finally:
    with TestSession() as session:
      session.connection().execute(
        sa.delete(LogModel).where(
          col(LogModel.attributes)["inkcre.operation"].astext == operation
        )
      )
      session.commit()
